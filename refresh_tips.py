_VERSION_RE = re.compile(r"^##\s*\[?(\d+\.\d+\.\d+)\]?")
_COMMAND_TOKEN_RE = re.compile(r"`(/[a-z][a-z0-9-]*|--[a-z][a-z0-9-]*)`")
_ADDED_RE = re.compile(r"^(Added|New)\b", re.IGNORECASE)
# First clause only; a period ends a clause when followed by whitespace, except in "e.g."
_CLAUSE_END_RE = re.compile(r"(?<!e\.g)\.\s|;\s| — | -- ")

AI_SCHEMA = json.dumps({
    "type": "object",
    "properties": {
        "tips": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "cmd": {"type": "string"},
                    "text": {"type": "string"},
                },
                "required": ["cmd", "text"],
            },
        }
    },
    "required": ["tips"],
})

AI_PROMPT = (
    "You are curating power-user tips for the Claude Code CLI status line. "
    "Write 8 fresh, genuinely useful tips about lesser-known Claude Code SLASH "
    "COMMANDS. Rules: (1) 'cmd' must be an exact real slash command starting "
    "with '/'. These are known-real commands for reference: {cmds}. Prefer the "
    "less obvious ones; you may also use a newer command not in that list if "
    "you are certain it exists in the current Claude Code. Never invent a "
    "command. (2) 'text' is a crisp, ACCURATE imperative blurb of at most 62 "
    "characters, no trailing period, describing what the command actually does; "
    "if you are unsure what a command does, skip it. (3) Highlight a non-obvious "
    "angle or when to reach for it. Return JSON."
)


def _claude_bin():
    """Locate the claude CLI even under launchd, where PATH is bare."""
    for candidate in (Path.home() / ".local" / "bin" / "claude",
                      Path.home() / ".claude" / "launcher-bin" / "claude"):
        if candidate.is_file():
            return str(candidate)
    return shutil.which("claude")


def load_pool():
    try:
        pool = json.loads(POOL.read_text())
        if isinstance(pool, dict) and isinstance(pool.get("tips"), list):
            pool.setdefault("meta", {})
            return pool
    except (OSError, json.JSONDecodeError):
        pass
    return {"tips": [], "meta": {"seen_versions": [], "updated_at": 0}}


def save_pool(pool):
    pool.setdefault("meta", {})["updated_at"] = int(time.time())
    BASE.mkdir(parents=True, exist_ok=True)
    temp_path = POOL.with_suffix(".json.tmp")
    temp_path.write_text(json.dumps(pool, ensure_ascii=False, indent=1))
    temp_path.replace(POOL)


def _tip_key(cmd, text):
    return (cmd.strip().lower(), text.strip().lower())


def add_tips(pool, new_tips, src, extra=None):
    """Append tips whose (cmd, text) key is new. Returns the number added."""
    known_keys = {_tip_key(tip.get("cmd", ""), tip.get("text", "")) for tip in pool["tips"]}
    added = 0
    for cmd, text in new_tips:
        cmd, text = cmd.strip(), text.strip()
        if not cmd or not text:
            continue
        key = _tip_key(cmd, text)
        if key in known_keys:
            continue
        entry = {"cmd": cmd, "text": text, "src": src}
        if extra:
            entry.update(extra)
        pool["tips"].append(entry)
        known_keys.add(key)
        added += 1
    return added


def enforce_cap(pool):
    seed_tips = [tip for tip in pool["tips"] if tip.get("src") == "seed"]
    other_tips = [tip for tip in pool["tips"] if tip.get("src") != "seed"]
    pool["tips"] = seed_tips + other_tips[-MAX_NON_SEED:]


def cmd_seed(pool):
    added = add_tips(pool, SEED_TIPS, "seed")
    print(f"seed: +{added} (pool now {len(pool['tips'])})")
    return added


def _fetch(url, timeout=10):
    request = urllib.request.Request(url, headers={"User-Agent": "statusline-tips/1.0"})
    with urllib.request.urlopen(request, timeout=timeout) as response:
        return response.read().decode("utf-8", errors="replace")


def _bullet_to_tip(bullet, cmd):
    text = re.sub(r"`([^`]*)`", r"\1", bullet)
    text = re.sub(r"\[([^\]]*)\]\([^)]*\)", r"\1", text)
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"^(Added|New)\s+", "", text)
    if text.startswith(cmd + " "):
        text = text[len(cmd) + 1:]
    text = _CLAUSE_END_RE.split(text.strip().rstrip("."))[0].strip()
    if len(text) > 72:
        text = text[:71].rstrip() + "…"
    return text


def _parse_changelog(markdown):
    """Return [(version, [bullets])] newest first."""
    sections, version, bullets = [], None, []
    for line in markdown.splitlines():
        match = _VERSION_RE.match(line)
        if match:
            if version:
                sections.append((version, bullets))
            version, bullets = match.group(1), []
        elif version and line.lstrip().startswith("- "):
            bullets.append(line.lstrip()[2:].strip())
    if version:
        sections.append((version, bullets))
    return sections


def _changelog_tips(sections, seen_versions):
    new_tips, commands_used = [], set()
    for version, bullets in sections:
        if version in seen_versions:
            continue
        for bullet in bullets:
            bullet = bullet.strip()
            if not _ADDED_RE.match(bullet):
                continue
            tokens = _COMMAND_TOKEN_RE.findall(bullet)
            if not tokens or tokens[0] in commands_used:
                continue
            blurb = _bullet_to_tip(bullet, tokens[0])
            if len(blurb) < 8:
                continue
            commands_used.add(tokens[0])
            new_tips.append((tokens[0], blurb))
    return new_tips


def cmd_changelog(pool):
    meta = pool.setdefault("meta", {})
    seen_versions = set(meta.get("seen_versions", []))
    try:
        markdown = _fetch(CHANGELOG_URL)
    except (urllib.error.URLError, OSError) as error:
        print(f"changelog: fetch failed ({error})")
        return 0

    sections = _parse_changelog(markdown)
    if not sections:
        print("changelog: no sections parsed")
        return 0

    latest_version = sections[0][0]
    bootstrap = not seen_versions
    considered = sections[:CHANGELOG_BOOTSTRAP_VERSIONS] if bootstrap else sections
    new_tips = _changelog_tips(considered, seen_versions)
    if bootstrap:
        new_tips = new_tips[:CHANGELOG_BOOTSTRAP_TIPS]

    added = add_tips(pool, new_tips, "changelog", extra={"version": latest_version})
    meta["seen_versions"] = sorted(seen_versions | {version for version, _ in sections})
    meta["last_changelog_version"] = latest_version
    enforce_cap(pool)
    tag = " (bootstrap)" if bootstrap else ""
    print(f"changelog{tag}: +{added} from {len(considered)} versions "
          f"(latest {latest_version}, pool {len(pool['tips'])})")
    return added


def _known_slash_commands(pool):
    commands = {cmd for cmd, _ in SEED_TIPS if cmd.startswith("/")}
    commands.update(tip["cmd"] for tip in pool.get("tips", [])
                    if str(tip.get("cmd", "")).startswith("/"))
    return sorted(commands)


def _find_tips(node):
    """Find the first `tips` list inside the headless JSON output, including JSON nested in strings."""
    if isinstance(node, dict):
        if isinstance(node.get("tips"), list):
            return node["tips"]
        for value in node.values():
            found = _find_tips(value)
            if found:
                return found
    elif isinstance(node, str):
        try:
            return _find_tips(json.loads(node))
        except json.JSONDecodeError:
            return []
    return []


def _extract_ai_tips(raw_output):
    try:
        output = json.loads(raw_output)
    except json.JSONDecodeError:
        return []
    return [
        (str(tip["cmd"]), str(tip["text"]))
        for tip in _find_tips(output)
        if isinstance(tip, dict) and tip.get("cmd") and tip.get("text")
    ]


def _valid_ai_tip(cmd, text):
    cmd = cmd.strip()
    base_command = cmd.split()[0] if cmd else ""
    if not base_command.startswith("/"):
        return None
    text = re.sub(r"\s+", " ", text).strip().rstrip(".")
    if not 6 <= len(text) <= 74:
        return None
    return (base_command, text)


def cmd_ai(pool):
    claude = _claude_bin()
    if not claude:
        print("ai: claude binary not found")
        return 0

    prompt = AI_PROMPT.format(cmds=", ".join(_known_slash_commands(pool)))
    try:
        process = subprocess.run(
            [claude, "-p", prompt,
             "--model", "sonnet", "--tools", "",
             "--output-format", "json", "--json-schema", AI_SCHEMA],
            capture_output=True, text=True, timeout=300, stdin=subprocess.DEVNULL,
        )
    except (FileNotFoundError, subprocess.TimeoutExpired) as error:
        print(f"ai: claude call failed ({error})")
        return 0
    if process.returncode != 0:
        print(f"ai: claude exited {process.returncode}: {process.stderr[:200]}")
        return 0

    generated = _extract_ai_tips(process.stdout)
    if not generated:
        print("ai: no tips parsed from response")
        return 0

    valid = [tip for tip in (_valid_ai_tip(cmd, text) for cmd, text in generated) if tip]
    added = add_tips(pool, valid, "ai", extra={"gen": int(time.time())})
    enforce_cap(pool)
    print(f"ai: +{added} (of {len(generated)} generated, {len(generated) - len(valid)} skipped on format; "
          f"pool now {len(pool['tips'])})")
    return added


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--seed", action="store_true", help="add any missing curated seed tips")
    parser.add_argument("--changelog", action="store_true", help="mine unseen CHANGELOG versions for new commands")
    parser.add_argument("--ai", action="store_true", help="generate fresh tips with headless claude -p")
    args = parser.parse_args()
    if not (args.seed or args.changelog or args.ai):
        args.seed = args.changelog = True

    pool = load_pool()
    if args.seed:
        cmd_seed(pool)
    if args.changelog:
        cmd_changelog(pool)
    if args.ai:
        cmd_ai(pool)
    save_pool(pool)
    print(f"saved {POOL}")


if __name__ == "__main__":
    main()
